#[cfg(test)]
mod tests {
    use crate::testing::{assert_no_dates, check_dates};

    #[test]
    fn natural_language() {
        check_dates(&[
            ("now", "2026-10-13 21:24:16+02:00"),
            ("today", "2026-10-13 00:00:00+02:00"),
            ("tomorrow", "2026-10-14 00:00:00+02:00"),
            ("yesterday 18:00", "2026-10-12 18:00:00+02:00"),
            ("tomorrow at 9", "2026-10-14 09:00:00+02:00"),
            ("tomorrow at noon", "2026-10-14 12:00:00+02:00"),
            ("midnight", "2026-10-13 00:00:00+02:00"),
            ("9pm", "2026-10-13 21:00:00+02:00"),
            ("9:30 a.m. tomorrow", "2026-10-14 09:30:00+02:00"),
            ("12am", "2026-10-13 00:00:00+02:00"),
            ("12pm", "2026-10-13 12:00:00+02:00"),
            ("in 2 hours", "2026-10-13 23:24:16+02:00"),
            ("2h ago", "2026-10-13 19:24:16+02:00"),
            ("5m ago", "2026-10-13 21:19:16+02:00"),
            ("3 days ago", "2026-10-10 21:24:16+02:00"),
            ("in 1h 30m", "2026-10-13 22:54:16+02:00"),
            ("in an hour", "2026-10-13 22:24:16+02:00"),
            ("2 weeks from now", "2026-10-27 21:24:16+01:00"),
            ("next week", "2026-10-20 00:00:00+02:00"),
            ("next friday", "2026-10-16 00:00:00+02:00"),
            ("next tuesday", "2026-10-20 00:00:00+02:00"),
            ("last monday", "2026-10-12 00:00:00+02:00"),
            ("this friday", "2026-10-16 00:00:00+02:00"),
            ("next month", "2026-11-13 00:00:00+01:00"),
            ("the 14th", "2026-10-14 00:00:00+02:00"),
            ("friday the 13th", "2026-11-13 00:00:00+01:00"),
            ("24:00", "2026-10-14 00:00:00+02:00"),
        ]);
    }

    #[test]
    fn month_names() {
        check_dates(&[
            ("13 Oct 2026", "2026-10-13 00:00:00+02:00"),
            ("Oct 13, 2026", "2026-10-13 00:00:00+02:00"),
            ("October 13th 2026", "2026-10-13 00:00:00+02:00"),
            ("13th of October 2026", "2026-10-13 00:00:00+02:00"),
            ("13-Oct-2026", "2026-10-13 00:00:00+02:00"),
            ("13-Oct-26", "2026-10-13 00:00:00+02:00"),
            ("Oct 13 '26", "2026-10-13 00:00:00+02:00"),
            ("Oct 13, 2026 9:30 PM", "2026-10-13 21:30:00+02:00"),
            ("Oct 2026", "2026-10-01 00:00:00+02:00"),
            ("october", "2026-10-01 00:00:00+02:00"),
            ("Tuesday, October 13, 2026", "2026-10-13 00:00:00+02:00"),
        ]);
    }

    #[test]
    fn prose_without_dates() {
        assert_no_dates(&[
            "We may march on, sun or not, and do so at once; the jan of this story is a dec of cards.",
            "Sat down with a second cup, then wed my notes to the last draft of the week.",
            "Version 1.2.10 runs on 10.10.10.10 and you may call +49 30 1234567 for help.",
            // Polish month and weekday abbreviations
            "She bit her lip and began to sob; the pig ran back into its sty.",
        ]);
    }
}
