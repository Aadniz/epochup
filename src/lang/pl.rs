#[cfg(test)]
mod tests {
    use crate::testing::{assert_no_dates, check_dates};

    #[test]
    fn locale_formats() {
        check_dates(&[
            (
                "wto, 13 paź 2026, 21:24:16 CEST",
                "2026-10-13 21:24:16+02:00",
            ),
            ("wto, 13 paź 2026, 21:24:16", "2026-10-13 21:24:16+02:00"),
            ("wto, 13 paź 2026, 09:05:00", "2026-10-13 09:05:00+02:00"),
        ]);
    }

    #[test]
    fn polish() {
        check_dates(&[
            ("13 października 2026", "2026-10-13 00:00:00+02:00"),
            ("13 października 2026 r.", "2026-10-13 00:00:00+02:00"),
            (
                "13 pazdziernika 2026 r. o godz. 15:00",
                "2026-10-13 15:00:00+02:00",
            ),
            ("wtorek, 13 października 2026", "2026-10-13 00:00:00+02:00"),
            ("1 maja", "2027-05-01 00:00:00+02:00"),
            ("dzisiaj o 15:30", "2026-10-13 15:30:00+02:00"),
            ("jutro o 15", "2026-10-14 15:00:00+02:00"),
            ("jutro o 8 rano", "2026-10-14 08:00:00+02:00"),
            ("o 9 wieczorem", "2026-10-13 21:00:00+02:00"),
            ("o 3 po południu", "2026-10-13 15:00:00+02:00"),
            ("pojutrze", "2026-10-15 00:00:00+02:00"),
            ("za 3 dni", "2026-10-16 21:24:16+02:00"),
            ("za tydzień", "2026-10-20 21:24:16+02:00"),
            ("za pół godziny", "2026-10-13 21:54:16+02:00"),
            ("za dwie godziny", "2026-10-13 23:24:16+02:00"),
            ("3 dni temu", "2026-10-10 21:24:16+02:00"),
            ("tydzień temu", "2026-10-06 21:24:16+02:00"),
            ("w przyszły piątek", "2026-10-16 00:00:00+02:00"),
            ("w zeszły poniedziałek", "2026-10-12 00:00:00+02:00"),
            ("w przyszłym tygodniu", "2026-10-20 00:00:00+02:00"),
            ("w środę", "2026-10-14 00:00:00+02:00"),
        ]);
    }

    #[test]
    fn in_text() {
        check_dates(&[
            (
                "Spotkanie odbędzie się 13 października o 15:00 w sali 5",
                "2026-10-13 15:00:00+02:00",
            ),
            (
                "Widzimy się jutro o 8 rano, dobrze?",
                "2026-10-14 08:00:00+02:00",
            ),
        ]);
    }

    #[test]
    fn prose_without_dates() {
        assert_no_dates(&[
            "Nie wiem, czy to prawda, ale lis sobie poszedł do lasu.",
            "Mam dwa koty i jednego psa, a sie nie bój.",
            "Kawa o 15 osób za mało, a marca ani śladu.",
        ]);
    }
}
